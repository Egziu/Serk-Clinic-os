using System.Text.Json;
using System.Text.RegularExpressions;

namespace Serk.Clinic.ArchitectureTests;

/// <summary>
/// Supply-chain guard: every resolved NuGet package must declare a license, and copyleft/source-available licenses that
/// are incompatible with a proprietary commercial product require an explicit owner/counsel decision (they fail here).
/// Writes docs/security/THIRD_PARTY_NUGET.md when SERK_UPDATE_LICENSE_INVENTORY=1.
/// </summary>
public partial class DependencyLicenseTests
{
    private static readonly string[] Blocked = ["AGPL", "GPL", "LGPL", "SSPL", "BUSL", "CC-BY-NC", "Commons-Clause"];

    [Fact]
    public void No_blocked_licenses_in_resolved_packages()
    {
        var root = RepoRoot();
        var assets = Directory.GetFiles(Path.Combine(root, "src"), "project.assets.json", SearchOption.AllDirectories)
            .Concat(Directory.GetFiles(Path.Combine(root, "tests"), "project.assets.json", SearchOption.AllDirectories));
        var packages = new SortedDictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        string? packageFolder = null;
        foreach (var file in assets)
        {
            using var doc = JsonDocument.Parse(File.ReadAllText(file));
            packageFolder ??= doc.RootElement.GetProperty("packageFolders").EnumerateObject().First().Name;
            foreach (var lib in doc.RootElement.GetProperty("libraries").EnumerateObject().Where(l => l.Value.GetProperty("type").GetString() == "package"))
            {
                packages[lib.Name] = lib.Value.GetProperty("path").GetString()!;
            }
        }

        Assert.NotEmpty(packages);
        var rows = new List<string>();
        var violations = new List<string>();
        foreach (var (nameVersion, path) in packages)
        {
            var nuspec = Directory.GetFiles(Path.Combine(packageFolder!, path), "*.nuspec").Single();
            var xml = File.ReadAllText(nuspec);
            var expr = LicenseExpression().Match(xml) is { Success: true } m ? m.Groups[1].Value : null;
            var url = LicenseUrl().Match(xml) is { Success: true } u ? u.Groups[1].Value : null;
            var file = LicenseFile().IsMatch(xml) ? "(license file in package)" : null;
            var license = expr ?? file ?? url ?? "UNDECLARED";
            rows.Add($"| {nameVersion} | {license} |");
            if (expr is not null && Blocked.Any(b => Regex.IsMatch(expr, $@"\b{Regex.Escape(b)}\b", RegexOptions.IgnoreCase)))
            {
                violations.Add($"{nameVersion}: {expr}");
            }
        }

        if (Environment.GetEnvironmentVariable("SERK_UPDATE_LICENSE_INVENTORY") == "1")
        {
            File.WriteAllText(Path.Combine(root, "docs", "security", "THIRD_PARTY_NUGET.md"),
                "# Third-party NuGet packages (resolved, generated)\n\nGenerated by `DependencyLicenseTests` with `SERK_UPDATE_LICENSE_INVENTORY=1`. " +
                "Packages showing a license URL or file require manual review of the referenced text.\n\n| Package | License |\n|---|---|\n" + string.Join("\n", rows) + "\n");
        }

        Assert.True(violations.Count == 0, "Blocked licenses (owner/counsel decision required): " + string.Join("; ", violations));
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "SerkClinic.slnx")))
        {
            dir = dir.Parent;
        }

        return dir?.FullName ?? throw new DirectoryNotFoundException("Repository root not found.");
    }

    [GeneratedRegex("<license type=\"expression\">([^<]+)</license>")]
    private static partial Regex LicenseExpression();

    [GeneratedRegex("<licenseUrl>([^<]+)</licenseUrl>")]
    private static partial Regex LicenseUrl();

    [GeneratedRegex("<license type=\"file\">")]
    private static partial Regex LicenseFile();
}
